// Bundle figma-plugin/core.js + handlers/*.js into figma-plugin/code.js (the file Figma loads).
// Handlers are bundled so the plugin works even when the sandbox refuses eval;
// when eval works, the server replaces them live on every connect / file change.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = import.meta.dir;
const core = readFileSync(join(DIR, "figma-plugin/core.js"), "utf8");
const handlers = readdirSync(join(DIR, "handlers")).filter((f) => f.endsWith(".js")).sort();
const bundled = handlers.map((f) => `// ---- handlers/${f} ----\n(function (H, ctx, figma) {\n${readFileSync(join(DIR, "handlers", f), "utf8")}\n})(H, ctx, figma);`).join("\n\n");
writeFileSync(join(DIR, "figma-plugin/code.js"), `// GENERATED by build.ts — edit figma-plugin/core.js and handlers/*.js instead.\n${core}\n\n${bundled}\n`);
console.log(`figma-plugin/code.js · core + ${handlers.length} handler files`);

// MCP server bundle (node target, deps inlined) — the file Claude Code runs from .mcp.json.
const mcp = Bun.spawnSync(["bun", "build", "src/server.ts", "--target=node", "--format=esm", "--outfile", "server.js"], { cwd: join(DIR, "mcp"), stdout: "pipe", stderr: "pipe" });
if (mcp.exitCode !== 0) { console.error(mcp.stderr.toString()); process.exit(1); }
console.log("mcp/server.js · bundled for node");
